const LON0 = -168;
const LON_SPAN = 348;
const LAT0 = 79;
const LAT_SPAN = 134;

function inside(lon, lat, ring) {
  let hit = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

export const MAP_ASPECT = LON_SPAN / LAT_SPAN;

export function landDots(cols) {
  const rows = Math.round(cols / MAP_ASPECT);
  const dots = [];
  for (let r = 0; r < rows; r++) {
    const lat = LAT0 - ((r + 0.5) / rows) * LAT_SPAN;
    for (let c = 0; c < cols; c++) {
      const lon = LON0 + ((c + 0.5) / cols) * LON_SPAN;
      if (LAND.some((ring) => inside(lon, lat, ring))) dots.push({ c, r });
    }
  }
  return { dots, rows };
}
